# 2. Model evaluation report
# --------------------------------------------------------------------------------------
def model_evaluation() -> None:
    sup = js("supervised_summary.json")
    anom = js("anomaly_summary.json")
    cv = tbl("supervised_network_cv.csv")
    test = tbl("supervised_network_test.csv")
    mb = tbl("supervised_modbus_test.csv")
    multi = pd.read_csv(OUT_TABLES / "supervised_network_multiclass.csv", index_col=0)
    imp = tbl("supervised_network_importance.csv")
    thr = tbl("anomaly_network_thresholds.csv")
    thrb = tbl("anomaly_network_baseline_thresholds.csv")
    accval = tbl("anomaly_access_validation.csv")
    adv = tbl("adversarial_results.csv")
    risk = js("risk_adversarial_summary.json")
    bal = sup["network"]["class_balance"]

    def row(df, model):
        return df[df.model == model].iloc[0]

    rf, dt, lr = row(test, "random_forest"), row(test, "decision_tree"), row(test, "logistic_regression")

    lines = [
        "# Model evaluation report",
        "",
        "*Member A deliverable (data and modelling lead). Every figure is read from the "
        "pipeline outputs by `src/s17_member_a_pack.py`; nothing is typed in by hand.*",
        "",
        "## 1. What was modelled, and why",
        "",
        "Three modelling problems were set, each matching a question in the charter:",
        "",
        "1. **Network intrusion detection** on ToN_IoT Zeek flows - can an attack flow be "
        "separated from ordinary traffic? (charter question 1)",
        "2. **Attack family identification** - if it is an attack, which kind? This decides "
        "which playbook an analyst opens.",
        "3. **OT protocol abuse** on Modbus telemetry - the mining-specific case, since "
        "Modbus is the protocol that touches physical plant.",
        "",
        "## 2. Preparation and leakage control",
        "",
        f"The flow dataset contains **{sup['network']['rows_dropped_as_duplicate']:,} exact "
        f"duplicate rows**. These were removed *before* the train/test split, leaving "
        f"{sup['network']['rows_used']:,} rows. Splitting first would have allowed the same "
        "record to appear on both sides of the split and would have inflated every score.",
        "",
        f"Class balance in the modelling set: **{bal['attack']:,} attack** rows and "
        f"**{bal['normal']:,} normal** rows, so attacks are "
        f"{bal['attack_share']:.0%} of the data. The minority class here is *normal* "
        "traffic, which is the opposite of an operational network and matters for the "
        "anomaly work in section 5. Class weighting was applied in every classifier so the "
        "imbalance does not simply push predictions towards the majority.",
        "",
        "Features: 18 numeric flow measures (durations, byte and packet counts, ratios and "
        "logarithmic transforms, ports) and 3 categorical fields (`proto`, `service`, "
        "`conn_state`), one-hot encoded with rare categories grouped.",
        "",
        "## 3. Model selection",
        "",
        "Selection used 3-fold cross-validated F1 on the **training data only**. The test "
        "set was scored once, at the end.",
        "",
        "| Model | CV F1 (mean) | CV F1 (sd) |",
        "|---|---:|---:|",
    ]
    for r in cv.itertuples():
        lines.append(f"| {r.model} | {r.cv_f1_mean:.4f} | {r.cv_f1_sd:.4f} |")

    lines += [
        "",
        f"**Random Forest** was selected. The justification is not that it scored highest "
        "by a fraction, but that flow data is a mixture of skewed numeric measures and "
        "categorical protocol fields with strong interactions, which is exactly the "
        "structure a tree ensemble handles without scaling assumptions. Logistic regression "
        "is retained as a transparent baseline, and the decision tree as an auditable "
        "rule set an OT engineer can read.",
        "",
        "## 4. Held-out performance",
        "",
        "| Model | Accuracy | Precision | Recall | F1 | ROC-AUC | PR-AUC |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for r in test.itertuples():
        lines.append(f"| {r.model} | {r.accuracy:.4f} | {r.precision:.4f} | {r.recall:.4f} | "
                     f"{r.f1:.4f} | {r.roc_auc:.4f} | {r.pr_auc:.4f} |")

    lines += [
        "",
        "**Reading these numbers in security terms.** At the Random Forest's operating "
        f"point, recall of {rf.recall:.4f} means roughly "
        f"{(1 - rf.recall) * 10000:.0f} attack flows in every 10,000 would be missed, and "
        f"precision of {rf.precision:.4f} means about "
        f"{(1 - rf.precision) * 10000:.0f} false alarms per 10,000 flagged flows. For a SOC, "
        "the false-alarm rate is what decides whether the detector is usable at all, which "
        "is why precision is reported beside recall rather than accuracy alone.",
        "",
        f"Logistic regression reaches F1 {lr.f1:.4f}, so a large part of this problem is "
        "linearly separable, but it misses "
        f"{(1 - lr.recall) * 100:.1f}% of attacks against "
        f"{(1 - rf.recall) * 100:.1f}% for the forest. On 211,000 flows that difference is "
        "thousands of missed events.",
        "",
        "### Attack family identification",
        "",
        f"Macro-F1 **{sup['network']['multiclass_macro_f1']:.4f}** across "
        f"{len(multi) - 3} labelled families.",
        "",
        "| Family | Precision | Recall | F1 | Support |",
        "|---|---:|---:|---:|---:|",
    ]
    for idx, r in multi.iterrows():
        if idx in ("accuracy", "macro avg", "weighted avg"):
            continue
        lines.append(f"| {idx} | {r['precision']:.3f} | {r['recall']:.3f} | "
                     f"{r['f1-score']:.3f} | {int(r['support']):,} |")
    worst = multi.drop(index=[i for i in ("accuracy", "macro avg", "weighted avg")
                              if i in multi.index])["f1-score"].idxmin()
    lines += [
        "",
        f"The weakest class is **{worst}**, with only "
        f"{int(multi.loc[worst, 'support']):,} test examples. That is a data-volume "
        "limitation rather than a modelling failure, and it should be stated as such: a "
        "class with a few hundred examples cannot be evaluated with confidence.",
        "",
        "### Modbus telemetry (OT protocol)",
        "",
        "| Model | Accuracy | Precision | Recall | F1 |",
        "|---|---:|---:|---:|---:|",
    ]
    for r in mb.itertuples():
        lines.append(f"| {r.model} | {r.accuracy:.4f} | {r.precision:.4f} | {r.recall:.4f} | "
                     f"{r.f1:.4f} |")
    lines += [
        "",
        f"The gap here is the interesting result: logistic regression reaches F1 "
        f"{row(mb, 'logistic_regression').f1:.4f} while the forest reaches "
        f"{row(mb, 'random_forest').f1:.4f}. Register values from a manipulated Modbus "
        "device are not high or low in a straight line; they are abnormal in combination, "
        "so a linear model cannot separate them and a tree ensemble can.",
        "",
        "## 5. What the detector actually uses",
        "",
        "Permutation importance (mean F1 drop when a feature is shuffled):",
        "",
        "| Feature | Importance | SD |",
        "|---|---:|---:|",
    ]
    for r in imp.head(8).itertuples():
        lines.append(f"| `{r.feature}` | {r.importance:.4f} | {r.sd:.4f} |")
    lines += [
        "",
        f"`{imp.iloc[0]['feature']}` dominates. This is worth saying honestly in the "
        "defence: the model leans heavily on protocol and connection-state fields rather "
        "than on traffic volume, which is also why the evasion test in section 7 barely "
        "moves the score - the evasion we simulated changed volume, not protocol.",
        "",
        "## 6. Unsupervised detection",
        "",
        "Two framings were run on the same data, and the contrast is the main methodological "
        "finding of the project.",
        "",
        f"- **Fully unsupervised** (fit on everything, no labels): ROC-AUC "
        f"**{anom['network']['roc_auc_unsupervised']:.3f}** - below chance.",
        f"- **Novelty detection against a known-good baseline** (fit on normal traffic only, "
        f"scored on unseen flows): ROC-AUC **{anom['network']['roc_auc_clean_baseline']:.3f}**.",
        "",
        anom["network"]["interpretation"],
        "",
        "Operating points for the fully unsupervised run:",
        "",
        "| Alert budget (top %) | Flagged | Precision | Recall |",
        "|---|---:|---:|---:|",
    ]
    for r in thr.itertuples():
        lines.append(f"| top {100 * (1 - r.threshold_quantile):.0f}% | {r.flagged:,} | "
                     f"{r.precision:.3f} | {r.recall:.3f} |")
    lines += ["", "Operating points for the clean-baseline run:", "",
              "| Threshold quantile | Flagged | Precision | Recall |", "|---|---:|---:|---:|"]
    for r in thrb.itertuples():
        lines.append(f"| {r.threshold_quantile:.2f} | {r.flagged:,} | {r.precision:.3f} | "
                     f"{r.recall:.3f} |")

    lines += [
        "",
        "### Access behaviour (user-days)",
        "",
        "| Method | Flagged | Precision vs injected | Recall vs injected | ROC-AUC |",
        "|---|---:|---:|---:|---:|",
    ]
    for r in accval.itertuples():
        lines.append(f"| {r.method} | {r.flagged} | {r.precision_vs_injected:.3f} | "
                     f"{r.recall_vs_injected:.3f} | {r.roc_auc_vs_injected:.3f} |")
    lines += [
        "",
        "Isolation Forest separates the injected behaviour almost perfectly; Local Outlier "
        "Factor does not beat chance on the same features. The likely reason is that the "
        "injected behaviour is globally unusual rather than locally unusual - the accounts "
        "concerned sit far from the whole population, not just from their immediate "
        "neighbours - and LOF measures local density.",
        "",
        "**Threshold.** The operating threshold is the 98th percentile of the score, which "
        "flags about 2 per cent of user-days. That is an alerting budget decision, not a "
        "statistical one: it is roughly two cases per working day for a 114-account estate.",
        "",
        "## 7. Robustness and adversarial testing",
        "",
        "| Test | Setting | F1 | Change vs unmodified |",
        "|---|---|---:|---:|",
    ]
    for r in adv.itertuples():
        lines.append(f"| {r.test} | {r.setting} | {r.f1:.4f} | {r.f1_change_vs_baseline:+.4f} |")
    lines += [
        "",
        "**Interpretation.** Collection reliability is the biggest risk: losing half the "
        "fields costs more than a quarter of the F1, so telemetry completeness is itself a "
        "security control. Label poisoning has to reach roughly a third of the training set "
        "before it does comparable damage, which argues for controlling who can label data. "
        "The evasion test is the weakest of the four, because it perturbs volume features "
        "while the model relies on protocol fields - a stronger test is recorded as backlog "
        "item B02 rather than claimed as a result.",
        "",
        "## 8. Predictive risk model",
        "",
        f"The daily risk score separates the injected behaviour with ROC-AUC "
        f"**{risk['risk_score']['roc_auc_vs_injected']:.3f}** and precision at the top 20 "
        f"user-days of **{risk['risk_score']['precision_at_20']:.2f}**.",
        "",
        f"The next-day early-warning model is weak: ROC-AUC "
        f"**{risk['early_warning']['roc_auc']:.3f}** on a time-ordered split, against a base "
        f"rate of {risk['early_warning']['test_positive_rate']:.3f}. This is reported as a "
        "negative result. Alerts in this data are driven by single events rather than by a "
        "build-up in the preceding day's behaviour, so there is little for a next-day model "
        "to learn. A longer observation window, or event-level rather than day-level "
        "features, would be the next thing to try.",
        "",
        "## 9. Limitations that must be stated",
        "",
        "1. ToN_IoT is a controlled testbed. Scores near 1.0 reflect a clean laboratory "
        "capture, not what the same model would achieve on live mining traffic.",
        "2. Attacks are the majority class in the capture, which is unlike any real network "
        "and directly explains the unsupervised result in section 6.",
        "3. The access-behaviour results are measured against behaviour that we injected "
        "ourselves, so they demonstrate that the method works, not that an attacker was "
        "found.",
        "4. The Modbus and flow models are trained on the same testbed environment, so they "
        "would need recalibration against site data before any operational use.",
        "",
    ]
    (DOCS / "member_a_model_evaluation.md").write_text("\n".join(lines), encoding="utf-8")
    LOG.info("model evaluation report written")


