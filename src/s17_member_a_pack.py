"""
Stage 17 - Member A evidence pack (data and modelling lead deliverables).

The capstone specification, section 4.1, requires Member A to produce a data dictionary,
scripts/notebooks, an experiment log and a model evaluation. Those artefacts exist as CSV
and JSON across outputs/tables/, but a marker should not have to assemble them. This script
generates the three readable documents from the pipeline outputs, so every number in them
is the number the code produced on the last run.

Generated:
  docs/member_a_data_dictionary.md
  docs/member_a_model_evaluation.md
  docs/experiment_log.csv
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import OUT_TABLES, ROOT, get_logger

LOG = get_logger("s17_member_a")
DOCS = ROOT / "docs"
DOCS.mkdir(exist_ok=True)


def tbl(name: str) -> pd.DataFrame:
    return pd.read_csv(OUT_TABLES / name)


def js(name: str) -> dict:
    return json.loads((OUT_TABLES / name).read_text())


# --------------------------------------------------------------------------------------
# 1. Data dictionary document
# --------------------------------------------------------------------------------------
def data_dictionary() -> None:
    inv = tbl("data_inventory.csv")
    dic = tbl("data_dictionary.csv")
    clog = tbl("cleaning_log.csv")
    qual = tbl("data_quality.csv")

    lines = [
        "# Data inventory and data dictionary",
        "",
        "*Member A deliverable (data and modelling lead). Generated by "
        "`src/s17_member_a_pack.py` from the last pipeline run, so the figures match the "
        "code output exactly.*",
        "",
        "## 1. Inventory",
        "",
        f"{len(inv)} files, **{inv['rows'].sum():,} records** in total, drawn from five "
        "source families.",
        "",
        "| Dataset | Rows | Cols | Status | Role in the project | Time coverage | "
        "Duplicates | Labelled |",
        "|---|---:|---:|---|---|---|---:|---|",
    ]
    for r in inv.itertuples():
        cover = f"{str(r.time_from)[:10]} to {str(r.time_to)[:10]}" if str(r.time_from) != "nan" else "n/a"
        lines.append(f"| `{r.dataset}` | {r.rows:,} | {r.columns} | {r.data_status} | "
                     f"{r.project_role} | {cover} | {r.duplicate_rows:,} | "
                     f"{'yes (' + str(r.label_column) + ')' if r.labelled else 'no'} |")

    lines += [
        "",
        "Provenance hashes (SHA-256, first 16 characters) are stored in "
        "`outputs/tables/data_inventory.csv` so that a marker can confirm the raw inputs "
        "were not edited after analysis.",
        "",
        "## 2. Column dictionary by semantic role",
        "",
        "Each column was classified automatically into the role it plays in the analysis. "
        "This is how requirement C2 is demonstrated: identity/access, network/OT and "
        "asset-context fields all exist in the data, not only in the proposal.",
        "",
    ]
    role_counts = dic["semantic_role"].value_counts()
    lines.append("| Semantic role | Columns | Datasets |")
    lines.append("|---|---:|---|")
    for role, n in role_counts.items():
        ds = ", ".join(sorted(dic.loc[dic.semantic_role == role, "dataset"].unique())[:6])
        lines.append(f"| {role} | {n} | {ds} |")
    lines.append("")

    for ds in inv["dataset"]:
        sub = dic[dic.dataset == ds]
        if sub.empty:
            continue
        lines += [f"### `{ds}`", "",
                  "| Column | Type | Role | Non-null | Missing % | Distinct | Example |",
                  "|---|---|---|---:|---:|---:|---|"]
        for r in sub.itertuples():
            ex = str(r.example_values)[:48].replace("|", "/")
            lines.append(f"| `{r.column}` | {r.dtype} | {r.semantic_role} | {r.non_null:,} | "
                         f"{r.missing_pct} | {r.n_unique:,} | {ex} |")
        lines.append("")

    lines += [
        "## 3. Quality findings",
        "",
        f"{len(qual)} quality issues were recorded automatically before any cleaning was "
        "applied. The most common categories were:",
        "",
    ]
    for issue, n in qual["issue"].value_counts().items():
        lines.append(f"- **{issue}** - {n} occurrences")
    lines += [
        "",
        "## 4. Cleaning actions",
        "",
        f"{len(clog)} actions were logged. Every action records the dataset, what was done, "
        "why, and the row count before and after, so nothing changes silently.",
        "",
        "| Dataset | Action | Detail | Reason |",
        "|---|---|---|---|",
    ]
    for r in clog.itertuples():
        lines.append(f"| {r.dataset} | {r.action} | {str(r.detail)[:60]} | "
                     f"{str(r.reason)[:110]} |")
    lines += [
        "",
        "## 5. Decisions a marker may want to question",
        "",
        "- **Duplicates are flagged, not deleted, in the stored data.** The flag is used to "
        "exclude them from model training and testing, but the rows stay in the file so "
        "that no evidence is destroyed.",
        "- **Missing telemetry values are not imputed.** A gap in a sensor feed is treated "
        "as a gap, because an invented reading would teach the model a pattern that never "
        "happened.",
        "- **Zeek's `-` placeholder is treated as missing, not as a category.** Left as a "
        "string it would have become one of the strongest, and entirely artificial, "
        "predictors.",
        "- **The ToN_IoT flow mirror has no timestamp column**, so joins to that source are "
        "made on address and asset rather than on time. This is recorded as defect D01.",
        "",
    ]
    (DOCS / "member_a_data_dictionary.md").write_text("\n".join(lines), encoding="utf-8")
    LOG.info("data dictionary document written (%d columns documented)", len(dic))


